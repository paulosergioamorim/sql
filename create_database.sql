CREATE TABLE departamento (
 id_dep INTEGER PRIMARY KEY,
 nome VARCHAR(60) NOT NULL UNIQUE
);
CREATE TABLE professor (
 id_prof INTEGER PRIMARY KEY,
 nome VARCHAR(80) NOT NULL,
 id_dep INTEGER NOT NULL REFERENCES departamento(id_dep),
 salario NUMERIC(10,2) CHECK (salario >= 0)
);
CREATE TABLE aluno (
 id_aluno INTEGER PRIMARY KEY,
 nome VARCHAR(60) NOT NULL,
 cidade VARCHAR(60) NOT NULL,
 bolsa NUMERIC(10,2) CHECK (bolsa >= 0),
 email VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE disciplina (
 id_disc INTEGER PRIMARY KEY,
 nome VARCHAR(80) NOT NULL UNIQUE,
 id_dep INTEGER NOT NULL REFERENCES departamento(id_dep),
 carga_horaria INTEGER NOT NULL CHECK (carga_horaria > 0),
 obrigatoria CHAR(1) NOT NULL CHECK (obrigatoria IN ('S','N'))
);
CREATE TABLE pre_requisito (
 id_disc INTEGER REFERENCES disciplina(id_disc),
 id_pre INTEGER REFERENCES disciplina(id_disc),
 PRIMARY KEY (id_disc, id_pre),
 CHECK (id_disc <> id_pre)
);
CREATE TABLE turma (
 id_turma INTEGER PRIMARY KEY,
 id_disc INTEGER NOT NULL REFERENCES disciplina(id_disc),
 id_prof INTEGER NOT NULL REFERENCES professor(id_prof),
 ano INTEGER NOT NULL CHECK (ano BETWEEN 2000 AND 2100),
 semestre INTEGER NOT NULL CHECK (semestre IN (1,2)),
 vagas INTEGER NOT NULL CHECK (vagas > 0)
);
CREATE TABLE matricula (
 id_aluno INTEGER REFERENCES aluno(id_aluno),
 id_turma INTEGER REFERENCES turma(id_turma),
 nota NUMERIC(4,2) CHECK (nota BETWEEN 0 AND 10),
 frequencia NUMERIC(5,2) CHECK (frequencia BETWEEN 0 AND 100),
 situacao VARCHAR(10) NOT NULL CHECK
  (situacao IN ('APROVADO','REPROVADO','CURSANDO','TRANCADO')),
 PRIMARY KEY (id_aluno, id_turma),
 CHECK ((situacao = 'APROVADO' AND nota IS NOT NULL
         AND frequencia IS NOT NULL AND nota >= 7 AND frequencia >= 75)
     OR (situacao = 'REPROVADO' AND nota IS NOT NULL
         AND frequencia IS NOT NULL AND (nota < 7 OR frequencia < 75))
     OR (situacao IN ('CURSANDO','TRANCADO')
         AND nota IS NULL AND frequencia IS NULL))
);
CREATE TABLE projeto (
 id_proj INTEGER PRIMARY KEY,
 nome VARCHAR(80) NOT NULL UNIQUE,
 id_dep INTEGER NOT NULL REFERENCES departamento(id_dep),
 orcamento NUMERIC(12,2) NOT NULL CHECK (orcamento >= 0)
);
CREATE TABLE participacao (
 id_aluno INTEGER REFERENCES aluno(id_aluno),
 id_proj INTEGER REFERENCES projeto(id_proj),
 papel VARCHAR(10) NOT NULL CHECK (papel IN ('BOLSISTA','VOLUNTARIO')),
 horas NUMERIC(7,2) CHECK (horas >= 0),
 PRIMARY KEY (id_aluno, id_proj)
);

